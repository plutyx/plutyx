create table if not exists public.storefronts (
  id bigint generated by default as identity primary key,
  business_id bigint not null references public.businesses(id) on delete cascade,
  brand_id bigint references public.brands(id) on delete set null,
  channel_id bigint not null references public.channels(id) on delete restrict,
  slug varchar(60) not null,
  display_name varchar(160) not null,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint ck_storefront_slug check (slug ~ '^[a-z0-9][a-z0-9-]{2,59}$')
);
create unique index if not exists uq_storefronts_slug on public.storefronts(lower(slug));
create index if not exists ix_storefronts_business on public.storefronts(business_id,active);
create index if not exists ix_storefronts_brand on public.storefronts(brand_id) where brand_id is not null;

create table if not exists public.order_attributions (
  id bigint generated by default as identity primary key,
  business_id bigint not null references public.businesses(id) on delete cascade,
  order_id bigint not null references public.orders(id) on delete cascade,
  storefront_id bigint references public.storefronts(id) on delete set null,
  session_key varchar(120),
  referrer varchar(500),
  utm_source varchar(120),
  utm_medium varchar(120),
  utm_campaign varchar(160),
  utm_content varchar(160),
  utm_term varchar(160),
  gclid varchar(220),
  fbclid varchar(220),
  ttclid varchar(220),
  media_cost_cents integer check (media_cost_cents is null or media_cost_cents >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(order_id)
);
create index if not exists ix_order_attributions_business_created on public.order_attributions(business_id,created_at desc);
create index if not exists ix_order_attributions_campaign on public.order_attributions(business_id,utm_source,utm_medium,utm_campaign);
create index if not exists ix_order_attributions_storefront on public.order_attributions(storefront_id) where storefront_id is not null;

create table if not exists public.conversion_events (
  id bigint generated by default as identity primary key,
  business_id bigint not null references public.businesses(id) on delete cascade,
  order_id bigint not null references public.orders(id) on delete cascade,
  attribution_id bigint references public.order_attributions(id) on delete set null,
  event_name varchar(40) not null default 'purchase',
  event_id varchar(180) not null,
  occurred_at timestamptz not null default now(),
  revenue_cents integer not null default 0,
  variable_cost_cents integer not null default 0,
  channel_cost_cents integer not null default 0,
  media_cost_cents integer not null default 0,
  contribution_after_media_cents integer not null default 0,
  status varchar(20) not null default 'pending' check (status in ('pending','processing','sent','failed','dead_letter')),
  attempts integer not null default 0 check (attempts >= 0),
  last_error text,
  payload_json text not null default '{}',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(event_id),
  unique(order_id,event_name)
);
create index if not exists ix_conversion_events_business_created on public.conversion_events(business_id,occurred_at desc);
create index if not exists ix_conversion_events_delivery on public.conversion_events(status,created_at) where status in ('pending','failed');

