declare role_name text; table_name text; seq_name text;
begin
  foreach role_name in array array['anon','authenticated'] loop
    if exists(select 1 from pg_roles where rolname=role_name) then
      foreach table_name in array array['commercial_plans','delivery_settings','customer_brand_profiles','delivery_route_batches','delivery_route_stops','delivery_driver_ledger'] loop
        execute format('revoke all privileges on table public.%I from %I',table_name,role_name);
      end loop;
      foreach seq_name in array array['customer_brand_profiles_id_seq','delivery_route_batches_id_seq','delivery_route_stops_id_seq','delivery_driver_ledger_id_seq'] loop
        if to_regclass('public.'||seq_name) is not null then execute format('revoke all privileges on sequence public.%I from %I',seq_name,role_name); end if;
      end loop;
    end if;
  end loop;
end $$;

