create or replace function public.c360_sync_customer_brand_profile() returns trigger
language plpgsql security definer set search_path=public as $$
declare paid_delta integer:=0; revenue_delta bigint:=0; contribution_delta bigint:=0;
begin
  if tg_op='INSERT' then
    if new.customer_id is null or new.brand_id is null then return new; end if;
    insert into public.customer_brand_profiles(business_id,brand_id,customer_id,first_order_at,last_order_at,order_count,paid_order_count,revenue_cents,contribution_cents)
    values(new.business_id,new.brand_id,new.customer_id,new.created_at,new.created_at,1,case when new.paid then 1 else 0 end,case when new.paid then new.total_cents else 0 end,case when new.paid then new.contribution_cents else 0 end)
    on conflict(business_id,brand_id,customer_id) do update set
      first_order_at=coalesce(public.customer_brand_profiles.first_order_at,excluded.first_order_at),
      last_order_at=greatest(coalesce(public.customer_brand_profiles.last_order_at,excluded.last_order_at),excluded.last_order_at),
      order_count=public.customer_brand_profiles.order_count+1,
      paid_order_count=public.customer_brand_profiles.paid_order_count+excluded.paid_order_count,
      revenue_cents=public.customer_brand_profiles.revenue_cents+excluded.revenue_cents,
      contribution_cents=public.customer_brand_profiles.contribution_cents+excluded.contribution_cents;
    return new;
  end if;

  if old.customer_id is distinct from new.customer_id or old.brand_id is distinct from new.brand_id then return new; end if;
  if new.customer_id is null or new.brand_id is null then return new; end if;
  if coalesce(old.paid,false)=false and coalesce(new.paid,false)=true then
    paid_delta:=1; revenue_delta:=new.total_cents; contribution_delta:=new.contribution_cents;
  elsif coalesce(old.paid,false)=true and coalesce(new.paid,false)=false then
    paid_delta:=-1; revenue_delta:=-old.total_cents; contribution_delta:=-old.contribution_cents;
  elsif coalesce(new.paid,false)=true then
    revenue_delta:=new.total_cents-old.total_cents; contribution_delta:=new.contribution_cents-old.contribution_cents;
  end if;
  if paid_delta<>0 or revenue_delta<>0 or contribution_delta<>0 then
    update public.customer_brand_profiles set
      paid_order_count=greatest(0,paid_order_count+paid_delta),
      revenue_cents=revenue_cents+revenue_delta,
      contribution_cents=contribution_cents+contribution_delta,
      last_order_at=greatest(coalesce(last_order_at,new.updated_at),new.updated_at)
    where business_id=new.business_id and brand_id=new.brand_id and customer_id=new.customer_id;
  end if;
  return new;
end $$;

revoke all on function public.c360_sync_customer_brand_profile() from public;
do $$ begin
  if exists(select 1 from pg_roles where rolname='anon') then revoke all on function public.c360_sync_customer_brand_profile() from anon; end if;
  if exists(select 1 from pg_roles where rolname='authenticated') then revoke all on function public.c360_sync_customer_brand_profile() from authenticated; end if;
end $$;

