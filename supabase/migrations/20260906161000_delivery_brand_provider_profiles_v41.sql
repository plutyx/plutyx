create or replace function public.c360_validate_brand_integration_binding()
returns trigger
language plpgsql
security definer
set search_path=public
as $$
declare
  v_brand_business bigint;
  v_connection_business bigint;
  v_connection_provider text;
  v_channel_business bigint;
begin
  select business_id into v_brand_business from public.brands where id=new.brand_id and soft_deleted=false;
  if v_brand_business is null or v_brand_business<>new.business_id then
    raise exception 'BRAND_BUSINESS_MISMATCH';
  end if;

  select business_id,provider into v_connection_business,v_connection_provider
    from public.integration_connections where id=new.connection_id;
  if v_connection_business is null or v_connection_business<>new.business_id then
    raise exception 'CONNECTION_BUSINESS_MISMATCH';
  end if;
  if lower(coalesce(v_connection_provider,''))<>lower(coalesce(new.provider,'')) then
    raise exception 'CONNECTION_PROVIDER_MISMATCH';
  end if;

  if new.channel_id is not null then
    select business_id into v_channel_business from public.channels where id=new.channel_id;
    if v_channel_business is null or v_channel_business<>new.business_id then
      raise exception 'CHANNEL_BUSINESS_MISMATCH';
    end if;
  end if;
  return new;
end;
$$;

create or replace function public.c360_validate_brand_fiscal_profile()
returns trigger
language plpgsql
security definer
set search_path=public
as $$
declare v_brand_business bigint;
begin
  select business_id into v_brand_business from public.brands where id=new.brand_id and soft_deleted=false;
  if v_brand_business is null or v_brand_business<>new.business_id then
    raise exception 'BRAND_BUSINESS_MISMATCH';
  end if;
  if new.issuance_enabled and (nullif(trim(coalesce(new.fiscal_provider,'')),'') is null or nullif(trim(coalesce(new.provider_profile_ref,'')),'') is null) then
    raise exception 'FISCAL_PROVIDER_REQUIRED';
  end if;
  return new;
end;
$$;

revoke all on function public.c360_validate_brand_integration_binding() from public;
revoke all on function public.c360_validate_brand_fiscal_profile() from public;

drop trigger if exists trg_validate_brand_integration_binding on public.brand_integration_bindings;
create trigger trg_validate_brand_integration_binding
before insert or update on public.brand_integration_bindings
for each row execute function public.c360_validate_brand_integration_binding();

