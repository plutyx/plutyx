declare role_name text; seq_name text;
begin
  foreach role_name in array array['anon','authenticated'] loop
    if exists(select 1 from pg_roles where rolname=role_name) then
      execute format('revoke all privileges on table public.brand_integration_bindings from %I',role_name);
      execute format('revoke all privileges on table public.brand_fiscal_profiles from %I',role_name);
