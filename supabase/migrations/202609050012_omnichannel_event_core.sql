create or replace function public.c360_ingest_integration_event(
  p_business_id bigint,
  p_provider text,
  p_external_event_id text,
  p_event_type text,
  p_external_order_id text,
  p_occurred_at timestamptz,
  p_payload_sha256 text,
  p_payload_json text,
  p_signature_verified boolean,
  p_connection_id bigint default null
) returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_existing public.integration_events%rowtype;
  v_event public.integration_events%rowtype;
  v_provider text := lower(trim(coalesce(p_provider,'')));
begin
  if v_provider = '' then raise exception 'PROVIDER_REQUIRED'; end if;
  if nullif(trim(coalesce(p_external_event_id,'')),'') is null then raise exception 'EXTERNAL_EVENT_ID_REQUIRED'; end if;
  if nullif(trim(coalesce(p_event_type,'')),'') is null then raise exception 'EVENT_TYPE_REQUIRED'; end if;
  if p_payload_sha256 !~ '^[0-9a-fA-F]{64}$' then raise exception 'PAYLOAD_SHA256_INVALID'; end if;
  if nullif(p_payload_json,'') is null then raise exception 'PAYLOAD_REQUIRED'; end if;

  if p_connection_id is not null and not exists(
    select 1 from public.integration_connections
     where id=p_connection_id and business_id=p_business_id and lower(provider)=v_provider
  ) then
    raise exception 'INTEGRATION_CONNECTION_NOT_FOUND';
  end if;

  perform pg_advisory_xact_lock(hashtextextended(p_business_id::text || ':' || v_provider || ':' || p_external_event_id,0));

  select * into v_existing
    from public.integration_events
   where business_id=p_business_id
     and lower(provider)=v_provider
     and external_event_id=p_external_event_id
   limit 1;

  if found then
    return jsonb_build_object(
      'id',v_existing.id,
      'status',v_existing.status,
      'signature_verified',v_existing.signature_verified,
      'idempotent_replay',true
    );
  end if;

  insert into public.integration_events(
    business_id,connection_id,provider,external_event_id,event_type,external_order_id,
    occurred_at,signature_verified,payload_sha256,payload_json,status
  ) values (
    p_business_id,p_connection_id,v_provider,p_external_event_id,trim(p_event_type),nullif(trim(coalesce(p_external_order_id,'')),''),
    p_occurred_at,coalesce(p_signature_verified,false),lower(p_payload_sha256),p_payload_json,'received'
  ) returning * into v_event;

  if p_connection_id is not null then
    update public.integration_connections
       set last_event_at=now(),
           status=case when status in ('inactive','connecting','degraded') then 'active' else status end
     where id=p_connection_id;
  end if;

  insert into public.outbox_events(business_id,topic,payload_json)
  values(p_business_id,'integration.event.received',jsonb_build_object(
    'integration_event_id',v_event.id,'provider',v_provider,'external_event_id',p_external_event_id,
    'event_type',p_event_type,'signature_verified',coalesce(p_signature_verified,false)
  )::text);

  return jsonb_build_object(
    'id',v_event.id,
    'status',v_event.status,
    'signature_verified',v_event.signature_verified,
    'idempotent_replay',false
  );
end;
$$;

create or replace function public.c360_mark_integration_event(
  p_event_id bigint,
  p_status text,
  p_canonical_event_type text default null,
  p_normalized_json text default null,
  p_canonical_order_id bigint default null,
  p_error text default null,
  p_next_retry_at timestamptz default null
) returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_event public.integration_events%rowtype;
  v_status text := lower(trim(coalesce(p_status,'')));
begin
  if v_status not in ('processing','processed','ignored','failed','dead_letter') then
    raise exception 'INTEGRATION_STATUS_INVALID';
  end if;

  select * into v_event from public.integration_events where id=p_event_id for update;
  if not found then raise exception 'INTEGRATION_EVENT_NOT_FOUND'; end if;

  update public.integration_events
     set status=v_status,
         attempts=case when v_status='processing' then attempts+1 else attempts end,
         processing_started_at=case when v_status='processing' then now() else processing_started_at end,
         processed_at=case when v_status in ('processed','ignored') then now() else processed_at end,
         canonical_event_type=coalesce(nullif(trim(coalesce(p_canonical_event_type,'')),''),canonical_event_type),
         normalized_json=coalesce(p_normalized_json,normalized_json),
         canonical_order_id=coalesce(p_canonical_order_id,canonical_order_id),
         last_error=case when v_status in ('failed','dead_letter') then nullif(p_error,'') else null end,
         next_retry_at=case when v_status='failed' then p_next_retry_at else null end
   where id=p_event_id
   returning * into v_event;

  update public.integration_connections c
     set last_success_at=case when v_status in ('processed','ignored') then now() else c.last_success_at end,
         last_error_at=case when v_status in ('failed','dead_letter') then now() else c.last_error_at end,
         last_error=case when v_status in ('failed','dead_letter') then nullif(p_error,'') else null end,
         status=case when v_status='dead_letter' then 'degraded' when v_status in ('processed','ignored') and c.status='degraded' then 'active' else c.status end
    from public.integration_events e
   where e.id=p_event_id and c.id=e.connection_id;

  insert into public.outbox_events(business_id,topic,payload_json)
  values(v_event.business_id,'integration.event.' || v_status,jsonb_build_object(
    'integration_event_id',v_event.id,'provider',v_event.provider,'status',v_status,
    'canonical_event_type',v_event.canonical_event_type,'canonical_order_id',v_event.canonical_order_id
  )::text);

  return jsonb_build_object('id',v_event.id,'status',v_event.status,'attempts',v_event.attempts);
end;
$$;

create or replace function public.c360_requeue_integration_event(p_event_id bigint)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_event public.integration_events%rowtype;
begin
  select * into v_event from public.integration_events where id=p_event_id for update;
  if not found then raise exception 'INTEGRATION_EVENT_NOT_FOUND'; end if;
  if v_event.status not in ('failed','dead_letter') then raise exception 'INTEGRATION_EVENT_NOT_RETRYABLE'; end if;

  update public.integration_events
     set status='received',next_retry_at=null,last_error=null,processing_started_at=null,processed_at=null
   where id=p_event_id
   returning * into v_event;

  insert into public.outbox_events(business_id,topic,payload_json)
  values(v_event.business_id,'integration.event.requeued',jsonb_build_object('integration_event_id',v_event.id,'provider',v_event.provider)::text);

  return jsonb_build_object('id',v_event.id,'status',v_event.status,'attempts',v_event.attempts);
end;
$$;

