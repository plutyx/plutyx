begin;

create table if not exists public.integration_connections (
  id bigint generated by default as identity primary key,
  business_id bigint not null references public.businesses(id) on delete cascade,
  provider varchar(40) not null,
  external_account_ref varchar(160),
  display_name varchar(160),
  mode varchar(20) not null default 'webhook' check (mode in ('webhook','polling','manual')),
  status varchar(20) not null default 'inactive' check (status in ('inactive','connecting','active','degraded','disabled')),
  last_event_at timestamptz,
  last_success_at timestamptz,
  last_error_at timestamptz,
  last_error text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create unique index if not exists uq_integration_connections_business_provider_account
  on public.integration_connections(business_id, lower(provider), coalesce(external_account_ref,''));
create index if not exists ix_integration_connections_business_status
  on public.integration_connections(business_id,status);

create table if not exists public.integration_events (
  id bigint generated by default as identity primary key,
  business_id bigint not null references public.businesses(id) on delete cascade,
  connection_id bigint references public.integration_connections(id) on delete set null,
  provider varchar(40) not null,
  external_event_id varchar(200) not null,
  event_type varchar(120) not null,
  external_order_id varchar(200),
  occurred_at timestamptz,
  signature_verified boolean not null default false,
  payload_sha256 char(64) not null,
  payload_json text not null,
  canonical_event_type varchar(80),
  normalized_json text,
  canonical_order_id bigint references public.orders(id) on delete set null,
  status varchar(20) not null default 'received' check (status in ('received','processing','processed','ignored','failed','dead_letter')),
  attempts integer not null default 0 check (attempts >= 0),
  received_at timestamptz not null default now(),
  processing_started_at timestamptz,
  processed_at timestamptz,
  next_retry_at timestamptz,
  last_error text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create unique index if not exists uq_integration_events_business_provider_event
  on public.integration_events(business_id, lower(provider), external_event_id);
create index if not exists ix_integration_events_business_status_received
  on public.integration_events(business_id,status,received_at desc);
create index if not exists ix_integration_events_provider_external_order
  on public.integration_events(provider,external_order_id)
  where external_order_id is not null;
create index if not exists ix_integration_events_retry
  on public.integration_events(status,next_retry_at)
  where status in ('failed','dead_letter');

alter table public.integration_connections enable row level security;
alter table public.integration_events enable row level security;

do $$
begin
  if exists(select 1 from pg_roles where rolname='anon') then
    execute 'revoke all privileges on table public.integration_connections from anon';
    execute 'revoke all privileges on table public.integration_events from anon';
    execute 'revoke all privileges on sequence public.integration_connections_id_seq from anon';
    execute 'revoke all privileges on sequence public.integration_events_id_seq from anon';
  end if;
  if exists(select 1 from pg_roles where rolname='authenticated') then
    execute 'revoke all privileges on table public.integration_connections from authenticated';
    execute 'revoke all privileges on table public.integration_events from authenticated';
    execute 'revoke all privileges on sequence public.integration_connections_id_seq from authenticated';
    execute 'revoke all privileges on sequence public.integration_events_id_seq from authenticated';
  end if;
end $$;

